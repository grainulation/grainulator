  const session = importSession(JSON.parse(exported));
  assert.equal(session.steps.length, 3);
  await page.locator('#import-session').setInputFiles({ name: 'session.json', mimeType: 'application/json', buffer: Buffer.from(exported) });
  await page.getByText('Session opened.', { exact: false }).waitFor();
  assert.equal(await page.locator('#api-key').inputValue(), '');
  assert.equal(await page.locator('.pass-result').count(), 3);
