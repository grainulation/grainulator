  await page.locator('#stop').click();
  await page.waitForFunction(() => document.querySelector('#run-status').textContent === 'cancelled');
  assert.equal(await page.locator('#question').inputValue(), 'Preserve this when stopping');
  assert.equal(await page.locator('#setup-fields').isEnabled(), true);
  await page.waitForTimeout(350);
  assert.equal(await page.locator('#run-status').textContent(), 'cancelled', 'late response must not overwrite stopped state');
  await page.locator('#restart').click();
  await page.locator('#sample').click();
  assert.equal(await page.locator('#run').isDisabled(), true, 'sample gate must block synthesis');
  assert.match(await page.locator('#evidence-status').textContent(), /r002/);
  const claimsDownload = page.waitForEvent('download');
  await page.locator('#export-claims').click();
  const claimsFile = await claimsDownload;
  const claims = JSON.parse(fs.readFileSync(await claimsFile.path(), 'utf8'));
  assert.equal(claims.claims[0].evidence, 'stated');
  assert.equal(claims.claims.length, 3);
  await page.locator('#restart').click();
  assert.equal(await page.locator('#evidence-gate').isDisabled(), true);
  await page.locator('#ledger').check();
  await page.locator('#evidence-gate').check();
  await page.locator('#blind-spots').check();
  assert.match(await page.locator('#workflow-summary').textContent(), /5 model passes/);
  await page.locator('#question').fill('Show the feature workflow');
  await page.unroute('**/api/research/pass');
  const featureRequests = [];
  await page.route('**/api/research/pass', route => {
    const req = route.request().postDataJSON(); featureRequests.push(req);
    const text = req.system.includes('Return ONLY JSON') ? JSON.stringify({claims: [{id:'r001',type:'factual',topic:'cache',content:'Isolation holds.',sources:[],conflicts_with:[]}]}) : 'Model pass result';
    return route.fulfill({contentType:'application/x-ndjson',body:JSON.stringify({type:'result',result:{text,model:req.config.model}})+'\n'});
  });
  await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#run-status').textContent === 'blocked');
  assert.equal(featureRequests.length, 4, 'five-pass workflow must stop before synthesis');
  assert.equal(await page.locator('.pass-result').count(), 4);
  assert.equal(await page.locator('#run').isDisabled(), true);
  const gatedDownload = page.waitForEvent('download');
  await page.locator('#export-session').click();
  const gated = JSON.parse(fs.readFileSync(await (await gatedDownload).path(), 'utf8'));
  assert.equal(gated.config.blindSpots, true); assert.equal(gated.config.evidenceGate, true);
  await page.locator('#evidence-gate').uncheck();
  await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#run-status').textContent === 'complete');
  assert.equal(featureRequests.length, 9, 'gate off permits all five passes');
  await page.locator('#ledger').uncheck();
  assert.equal(await page.locator('#evidence-gate').isChecked(), false);
  assert.equal(await page.locator('#evidence-gate').isDisabled(), true);
  await page.locator('#restart').click();
  await page.locator('#sample').click();
  // Safe formatting: model HTML and javascript links must not execute.
  await page.evaluate(async () => {
    const { renderText } = await import('/research/render-text.js');
    const target = document.createElement('div');
    renderText(target, '# Heading\n- **Evidence**\n<script>window.pwned=true</script>\n[x](javascript:alert(1))');
    if (target.querySelector('script') || target.querySelector('a[href^="javascript:"]') || !target.querySelector('h4') || !target.querySelector('strong')) throw Error('Unsafe or missing formatting');
  });
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}`);
    await page.waitForFunction(() => [...document.querySelectorAll('.settings textarea')].filter(el => el.getClientRects().length).every(el => el.scrollHeight <= el.clientHeight + 2));
    const help = page.getByRole('button', { name: 'About build a claims ledger' });
    await help.focus(); await page.keyboard.press('Enter');
    assert.equal(await help.getAttribute('aria-expanded'), 'true');
    assert.equal(await page.locator('#ledger-help').isVisible(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `help overflow at ${width}`);
    await page.keyboard.press('Escape');
    assert.equal(await help.getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'About build a claims ledger');
    await page.evaluate(() => scrollTo(0, 0));
    fs.mkdirSync('.dogfood/screenshots', { recursive: true });
    await page.screenshot({ path: `.dogfood/screenshots/playground-${width}.png`, fullPage: true });
    results.push({ width, overflow: false });
  }
  await page.locator('#context').fill('Long context that must remain visible. '.repeat(35));
  await page.waitForFunction(() => { const el = document.querySelector('#context'); return el.scrollHeight <= el.clientHeight + 2; });
  assert.ok(await page.locator('#context').evaluate(el => el.clientHeight > 150));
  const playgroundWidth = await page.locator('.page-shell').evaluate(el => el.getBoundingClientRect().width);
  assert.equal(await page.locator('header img').evaluate(el => el.naturalWidth > 0), true);
  await page.locator('header nav a').click();
  await page.locator('#page-title').waitFor();
  const homepageWidth = await page.locator('.page-shell').evaluate(el => el.getBoundingClientRect().width);
  assert.equal(homepageWidth, playgroundWidth, 'homepage and playground must share a shell width');
  await page.goto('http://127.0.0.1:4517/privacy.html');
  assert.equal(await page.locator('.page-shell').evaluate(el => el.getBoundingClientRect().width), homepageWidth);
  assert.equal(await page.locator('header img').evaluate(el => el.naturalWidth > 0), true);
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({width, height:1000});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `privacy overflow at ${width}`);
    await page.screenshot({path: `.dogfood/screenshots/privacy-${width}.png`,fullPage:true});
  }
  await page.locator('aside a[href="#keys"]').focus(); await page.keyboard.press('Enter');
  assert.equal(new URL(page.url()).hash, '#keys');
  await page.goto('http://127.0.0.1:4517/playground');
