  // Failed passes preserve completed work and resume without running research again.
  await page.unroute('**/api/research/pass');
  let calls = 0;
  await page.route('**/api/research/pass', route => {
    calls++;
    const event = calls === 2 ? { type: 'error', error: 'Fixture provider failure' } : { type: 'result', result: { text: `Useful result ${calls}`, model: 'another-model' } };
    return route.fulfill({ contentType: 'application/x-ndjson', body: JSON.stringify(event) + '\n' });
  });
  await page.locator('#run').click();
  await page.getByText('Fixture provider failure', { exact: true }).waitFor();
  assert.equal(await page.locator('.pass-result').count(), 1); // failed pass has no empty result panel
  await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#run-status').textContent === 'complete');
  assert.equal(calls, 4, 'resume should run challenge and synthesis only');
  const partial = { ...session, steps: session.steps.slice(0, 1) };
